/**
 * Moteur Payment Infrastructure — Typed Contracts for KaziBox Core Integration
 *
 * Client specifications:
 * - Moteur is the centralized payment infrastructure for all payment providers.
 * - KaziBox does NOT directly integrate pawaPay, Stripe, Paystack, or other providers.
 * - Priority countries: DR Congo (CD), Cameroon (CM), Senegal (SN), Côte d'Ivoire (CI).
 * - Payment description: "KaziBox".
 * - Supported payment methods depend on providers actually enabled in Moteur.
 * - Ambassador commissions, wallets, and payouts are handled entirely by Moteur.
 *   KaziBox only preserves and forwards referral attribution codes.
 */

export type MoteurCountryCode = 'CD' | 'CM' | 'SN' | 'CI';

export type MoteurCurrency = 'CDF' | 'USD' | 'XAF' | 'XOF';

export type MoteurPaymentStatus =
  | 'pending'
  | 'succeeded'
  | 'failed'
  | 'expired'
  | 'refunded'
  | 'cancelled';

export type MoteurBillingCycle = 'monthly' | 'yearly';

/**
 * Server-only configuration loaded strictly from process.env
 */
export interface MoteurConfig {
  baseUrl: string;
  apiKey: string;
  webhookSecret: string;
  environment: 'sandbox' | 'production';
  paymentDescription: string;
  timeoutMs: number;
}

/**
 * Priority country configuration metadata
 */
export interface MoteurCountryConfig {
  code: MoteurCountryCode;
  name: {
    fr: string;
    en: string;
  };
  currencies: MoteurCurrency[];
  defaultCurrency: MoteurCurrency;
  callingCode: string;
  /**
   * Providers are marked as pending until confirmed by Moteur backend.
   * KaziBox never claims a provider is available before confirmation.
   */
  providerStatus: 'pending_moteur_confirmation' | 'active' | 'unavailable';
  confirmedProviders: string[];
}

/**
 * Customer profile passed to Moteur checkout session
 */
export interface MoteurCustomerInfo {
  id?: string;
  name?: string;
  email?: string;
  phone?: string;
}

/**
 * Request to initiate a payment session via Moteur
 */
export interface MoteurInitiatePaymentRequest {
  /** Unique idempotency key generated by KaziBox */
  idempotencyKey: string;
  /** Fixed payment description: "KaziBox" */
  description: 'KaziBox' | string;
  /** Total amount to charge */
  amount: number;
  /** Currency code matching the workspace country */
  currency: MoteurCurrency | string;
  /** Target African country code */
  country: MoteurCountryCode;
  /** KaziBox workspace/company ID */
  companyId: string;
  /** Subscribed plan ID (e.g., 'single', 'bundle', 'all_access', 'custom') */
  planId: string;
  /** Module IDs to unlock upon payment success */
  moduleIds: string[];
  /** Billing cycle */
  billingCycle: MoteurBillingCycle;
  /** Customer info */
  customer?: MoteurCustomerInfo;
  /**
   * Optional referral attribution code (ambassador code).
   * Moteur calculates commissions and distributes payouts; KaziBox only preserves attribution.
   */
  referralCode?: string;
  /** Additional metadata forwarded to Moteur */
  metadata?: Record<string, string | number | boolean>;
  /** Callback URL where Moteur redirects the user after payment completion */
  returnUrl?: string;
  /** Optional webhook callback override if permitted by Moteur */
  callbackUrl?: string;
}

/**
 * Response from Moteur when initiating a payment session
 */
export interface MoteurInitiatePaymentResponse {
  success: boolean;
  sessionId: string;
  reference: string;
  status: MoteurPaymentStatus;
  checkoutUrl?: string;
  qrCodeUrl?: string;
  instructions?: {
    fr: string;
    en: string;
  };
  expiresAt?: string;
  errorCode?: string;
  errorMessage?: string;
  raw?: unknown;
}

/**
 * Request to verify status of an existing payment
 */
export interface MoteurVerifyPaymentRequest {
  reference: string;
  sessionId?: string;
}

/**
 * Status verification response from Moteur
 */
export interface MoteurVerifyPaymentResponse {
  success: boolean;
  reference: string;
  sessionId?: string;
  status: MoteurPaymentStatus;
  amount: number;
  currency: string;
  companyId: string;
  planId: string;
  moduleIds: string[];
  billingCycle: MoteurBillingCycle;
  paidAt?: string;
  referralCode?: string;
  providerReference?: string;
  providerName?: string;
  raw?: unknown;
}

/**
 * Request to refund a payment through Moteur
 */
export interface MoteurRefundRequest {
  reference: string;
  amount?: number;
  reason?: string;
}

export interface MoteurRefundResponse {
  success: boolean;
  reference: string;
  refundId: string;
  status: 'refunded' | 'pending';
  amount: number;
  currency: string;
  refundedAt: string;
  errorMessage?: string;
}

/**
 * Inbound webhook payload from Moteur
 */
export interface MoteurWebhookEvent {
  id: string;
  event:
    | 'payment.succeeded'
    | 'payment.failed'
    | 'payment.expired'
    | 'payment.refunded'
    | 'subscription.renewed';
  occurredAt: string;
  data: {
    reference: string;
    sessionId: string;
    status: MoteurPaymentStatus;
    amount: number;
    currency: string;
    companyId: string;
    planId: string;
    moduleIds: string[];
    billingCycle: MoteurBillingCycle;
    paidAt?: string;
    refundedAt?: string;
    referralCode?: string;
    providerReference?: string;
    metadata?: Record<string, unknown>;
  };
  signature?: string;
}

/**
 * Result of handling an inbound payment confirmation in KaziBox
 */
export interface EntitlementGrantResult {
  success: boolean;
  isDuplicate: boolean;
  companyId: string;
  status: 'active' | 'suspended' | 'expired' | 'cancelled';
  planId: string;
  activatedModuleIds: string[];
  currentPeriodStart?: string;
  currentPeriodEnd?: string;
  reference: string;
  message?: string;
}
